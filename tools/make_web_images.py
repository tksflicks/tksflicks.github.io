"""
Updates the website's photo galleries from the folders in media/.

HOW TO ADD PHOTOS
    1. Drop .jpg/.png files into an album folder:
           media/portrait/<album>/    or    media/landscape/<album>/
       A new album folder automatically gets its own card on the
       Portraits / Landscapes page (name it like band_photos -> "Band Photos").
       Put a photo named cover.jpg in an album to choose its card image;
       otherwise the first photo is used. The home page shows every photo.
    2. From the repo root run:   python tools/make_web_images.py
    3. Commit and push (include media/web/).
To remove a photo, delete it from its folder and run the script again.
Photos show in filename order; rename (e.g. 01_name.jpg) to reorder.

WHAT IT DOES
For every photo under media/ it writes web-sized copies to media/web/
(same folder layout), so pages don't download the 10 MB camera originals:
    name-600.jpg    gallery grid on phones / small columns
    name-1200.jpg   gallery grid on large / retina screens
    name-2000.jpg   the lightbox viewer
and writes media/web/photos.js, the list of every photo with its
[width, height]. index.js builds each gallery from that list using the
gallery's data-folder attribute, so no HTML or JS needs editing.

Originals are left untouched (the viewer's "open full size" button uses them).
Already-generated files are skipped unless the original is newer, and copies
of deleted photos are cleaned up. Requires:  pip install Pillow
"""
import json
import os

from PIL import Image, ImageOps

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MEDIA = os.path.join(ROOT, 'media')
OUT = os.path.join(MEDIA, 'web')

EXTENSIONS = ('.jpg', '.jpeg', '.png')
WIDTHS = [600, 1200, 2000]
QUALITY = 80


def find_photos():
    """Every photo under media/ (except media/web), in a stable sorted order."""
    for dirpath, dirs, files in os.walk(MEDIA):
        dirs[:] = sorted(d for d in dirs if os.path.join(dirpath, d) != OUT)
        for f in sorted(files, key=str.lower):
            if f.lower().endswith(EXTENSIONS):
                yield os.path.relpath(os.path.join(dirpath, f), MEDIA).replace(os.sep, '/')


def out_path(rel, width):
    base = os.path.splitext(rel)[0]
    return os.path.normpath(os.path.join(OUT, '%s-%d.jpg' % (base, width)))


def remove_orphans(keep):
    """Delete generated copies whose original photo no longer exists."""
    removed = 0
    for dirpath, _, files in os.walk(OUT, topdown=False):
        for f in files:
            path = os.path.normpath(os.path.join(dirpath, f))
            if f.endswith('.jpg') and path not in keep:
                os.remove(path)
                removed += 1
        if dirpath != OUT and not os.listdir(dirpath):
            os.rmdir(dirpath)
    return removed


def main():
    photos = {}
    keep = set()
    made = 0
    for rel in find_photos():
        src = os.path.join(MEDIA, rel)
        src_mtime = os.path.getmtime(src)
        targets = [(w, out_path(rel, w)) for w in WIDTHS]
        keep.update(t[1] for t in targets)
        stale = [t for t in targets if not os.path.exists(t[1]) or os.path.getmtime(t[1]) < src_mtime]

        with Image.open(src) as im:
            im = ImageOps.exif_transpose(im)   # respect camera rotation
            photos[rel] = [im.width, im.height]
            if not stale:
                continue
            im = im.convert('RGB')
            for w, dest in stale:
                os.makedirs(os.path.dirname(dest), exist_ok=True)
                copy = im.copy()
                if copy.width > w:
                    copy = copy.resize((w, round(copy.height * w / copy.width)), Image.LANCZOS)
                copy.save(dest, 'JPEG', quality=QUALITY, optimize=True, progressive=True)
                made += 1
        print('new  ', rel)

    removed = remove_orphans(keep)

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, 'photos.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/make_web_images.py - do not edit by hand.\n')
        f.write('// Every photo under media/ with its original [width, height].\n')
        f.write('window.PHOTOS = %s;\n' % json.dumps(photos, indent=1))
    old = os.path.join(OUT, 'sizes.js')   # replaced by photos.js
    if os.path.exists(old):
        os.remove(old)

    print('%d photos listed, %d images written, %d stale images removed' % (len(photos), made, removed))


if __name__ == '__main__':
    main()
